/** True when hit check id `check` is selected by `sel` (exact, or `sel` + a letter suffix). */
export const selects = (sel, check) =>
  check === sel ||
  (check.startsWith(sel) && /^[a-z]$/.test(check.slice(sel.length)));

/** Parse argv; throws (→ exit 2) on a malformed or unknown --check list. */
export function parseArgs(args) {
  const ci = args.indexOf("--check");
  if (ci < 0) return { only: null, stdout: args.includes("--stdout") };
  const list = args[ci + 1];
  if (!list || list.startsWith("--"))
    throw new Error(
      "--check needs a comma-separated list of check ids (e.g. S3,S9)",
    );
  const only = list.split(",").map((c) => c.trim());
  const unknown = only.filter((c) => !CHECK_IDS.some((id) => selects(c, id)));
  if (unknown.length)
    throw new Error(
      `unknown check id(s): ${unknown.join(", ")} (known: ${CHECK_IDS.join(" ")})`,
    );
  return { only, stdout: true };
}

function main() {
  let res;
  let opts;
  try {
    opts = parseArgs(process.argv.slice(2));
    res = runSweep(ROOT, opts.only);
  } catch (e) {
    console.error(`content-sweep: TOOL ERROR — ${e.message}`);
    process.exit(2);
  }
  const header =
    "check\tclass\tlocale\tbook\tfile:line\tzone\trender\tmatch\tcontext";
  const rows = res.hits.map((h) =>
    [
      h.check,
      h.cls,
      h.locale,
      h.book,
      `${h.file}:${h.line}`,
      h.zone,
      h.render,
      h.match,
      h.context,
    ]
      .map(tsv)
      .join("\t"),
  );
  // A filtered run never overwrites the committed snapshot.
  if (opts.only || opts.stdout) {
    console.log([header, ...rows].join("\n"));
    return;
  }
  const out = path.join(ROOT, "docs/audit/content-sweep");
  mkdirSync(out, { recursive: true });
  writeFileSync(
    path.join(out, "findings.tsv"),
    `${[header, ...rows].join("\n")}\n`,
  );
  writeFileSync(
    path.join(out, "names.tsv"),
    `${["class\tlocale\ttranslit\tfamiliar\tcount\tbooks", ...res.names.map((n) => [n.cls, n.locale, n.translit, n.familiar, n.count, n.books].map(tsv).join("\t"))].join("\n")}\n`,
  );
  writeFileSync(path.join(out, "summary.md"), summary(res));
  console.log(
    `content-sweep: ${res.files} files, ${res.hits.length} hits, ${res.names.length} name pairs → docs/audit/content-sweep/`,
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  main();
