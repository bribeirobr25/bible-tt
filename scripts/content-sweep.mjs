#!/usr/bin/env node
// Content sweep — Launch Program Step 3 (docs/audit/PLAN_CONTENT_SWEEP.md).
// Read-only rule-compliance scan of content/{locale}/{book}/**.md. Findings are
// data (exit 0); a tool failure exits 2. Deterministic output.
//
//   node scripts/content-sweep.mjs              # writes docs/audit/content-sweep/
//   node scripts/content-sweep.mjs --check S3,S9 --stdout   # print selected checks as TSV

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  chapterModel,
  PER_FILE,
  s5d,
  s6f,
  s6s7,
  s7a,
  s19,
  s21,
} from "./sweep/checks.mjs";
import {
  esAccents,
  nameInventory,
  repeatedGlosses,
  variantCounts,
  verseParity,
} from "./sweep/corpus.mjs";
import { extractNameTables, extractTableCells } from "./sweep/rule-tables.mjs";
import { zoneLines } from "./sweep/zones.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = ["en", "pt-br", "de", "es"];

export function listMd(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) out.push(...listMd(p));
    else if (name.endsWith(".md")) out.push(p);
  }
  return out;
}

/** Load every content file into a FileCtx. Throws (tool error) on an empty corpus or unresolvable zones. */
export function loadCorpus(root = ROOT) {
  const content = path.join(root, "content");
  const books = readdirSync(path.join(content, "en"))
    .filter((b) => statSync(path.join(content, "en", b)).isDirectory())
    .sort();
  if (!books.length) throw new Error("no books under content/en");
  const ctxs = [];
  for (const locale of LOCALES)
    for (const book of books) {
      const dir = path.join(content, locale, book);
      if (!existsSync(dir)) continue;
      for (const file of listMd(dir)) {
        // NFC: a decomposed accent must not split a word or defeat a match
        const text = readFileSync(file, "utf8").normalize("NFC");
        const rel = path.relative(content, file).split(path.sep).join("/");
        const lines = text.split("\n");
        ctxs.push({
          path: `content/${rel}`,
          key: rel,
          locale,
          book,
          lines,
          zones: zoneLines(text, rel),
        });
      }
    }
  if (!ctxs.length) throw new Error("content sweep found no files");
  return { ctxs, books };
}

export function runSweep(root = ROOT, only = null) {
  const { ctxs } = loadCorpus(root);
  const rules = ["RULES-HB.md", "RULES-GS.md"].map((f) => [
    f,
    readFileSync(path.join(root, "docs/rules", f), "utf8"),
  ]);
  const table = rules.flatMap(([f, md]) => extractNameTables(md, f));
  const glossaryCells = new Set(
    rules.flatMap(([f, md]) => [...extractTableCells(md, f)]),
  );
  const familiarNames = new Set(
    table.flatMap((r) => Object.values(r.familiar)),
  );
  const hits = [];
  const add = (h) => {
    if (!only || only.some((c) => selects(c, h.check))) hits.push(h);
  };
  const models = new Map();
  const ran = new Map(); // check fn name → files examined
  for (const ctx of ctxs) {
    for (const fn of PER_FILE) {
      fn(ctx, add);
      ran.set(fn.name, (ran.get(fn.name) ?? 0) + 1);
    }
    s5d(ctx, add, familiarNames);
    const model = chapterModel(ctx);
    if (model) models.set(ctx.key, model);
    s6s7(ctx, add, model);
    s6f(ctx, add, model);
    s19(ctx, add, model);
    s21(ctx, add, glossaryCells);
  }
  for (const ctx of ctxs)
    s7a(ctx, add, models.get(ctx.key.replace(/^[^/]+\//, "en/")));
  verseParity(new Map(ctxs.map((c) => [c.key, c])), models, add);
  repeatedGlosses(ctxs, add);
  const names = nameInventory(ctxs, table, add);
  const variants = variantCounts(ctxs);
  esAccents(ctxs, add);
  // Code-point order (not localeCompare): byte-identical output on every machine.
  const cp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
  hits.sort(
    (a, b) =>
      cp(a.check, b.check) ||
      cp(a.file, b.file) ||
      a.line - b.line ||
      cp(a.match, b.match) ||
      cp(a.cls, b.cls),
  );
  return {
    hits,
    names,
    variants,
    files: ctxs.length,
    chapters: models.size,
    tableRows: table.length,
    ran,
  };
}

const tsv = (v) => String(v).replace(/[\t\n\r]/g, " ");

function summary({ hits, names, variants, files, chapters, tableRows }) {
  const out = [
    "# Content sweep — generated summary",
    "",
    "Generated by `pnpm content:sweep` (`scripts/content-sweep.mjs`). Do not edit by hand; interpretation lives in `docs/audit/CONTENT_SWEEP_FINDINGS.md`.",
    "",
    `Files scanned: **${files}** (chapters: ${chapters}) · name-table rows: ${tableRows} · hits: **${hits.length}**`,
    "",
    "## Counts by check × class × locale",
    "",
    "| Check | Class | EN | PT-BR | DE | ES | Total |",
    "|---|---|---:|---:|---:|---:|---:|",
  ];
  const agg = new Map();
  for (const h of hits) {
    const k = `${h.check}\u0000${h.cls}`;
    const e = agg.get(k) ?? { en: 0, "pt-br": 0, de: 0, es: 0 };
    e[h.locale]++;
    agg.set(k, e);
  }
  for (const [k, e] of [...agg].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    const [c, cls] = k.split("\u0000");
    const tot = e.en + e["pt-br"] + e.de + e.es;
    out.push(
      `| ${c} | ${cls.replace(/\|/g, "\\|")} | ${e.en} | ${e["pt-br"]} | ${e.de} | ${e.es} | ${tot} |`,
    );
  }
  out.push(
    "",
    "## Render state by check (now = visible to a reader · no = not shown)",
    "",
    "| Check | now | no |",
    "|---|---:|---:|",
  );
  const rend = new Map();
  for (const h of hits) {
    const e = rend.get(h.check) ?? { now: 0, no: 0 };
    e[h.render]++;
    rend.set(h.check, e);
  }
  for (const [c, e] of [...rend].sort((a, b) => (a[0] < b[0] ? -1 : 1)))
    out.push(`| ${c} | ${e.now} | ${e.no} |`);
  out.push("", "## Counts by check × book (all locales)", "");
  const books = [...new Set(hits.map((h) => h.book))].sort();
  out.push(
    `| Check | ${books.join(" | ")} |`,
    `|---|${books.map(() => "---:").join("|")}|`,
  );
  const byCheck = new Map();
  for (const h of hits) {
    const e = byCheck.get(h.check) ?? new Map();
    e.set(h.book, (e.get(h.book) ?? 0) + 1);
    byCheck.set(h.check, e);
  }
  for (const [c, e] of [...byCheck].sort((a, b) => (a[0] < b[0] ? -1 : 1)))
    out.push(`| ${c} | ${books.map((b) => e.get(b) ?? 0).join(" | ")} |`);
  out.push(
    "",
    "## Name pairs by class (S5)",
    "",
    "| Locale | tabled | conflict | reversed | untabled | (+multi-translit) |",
    "|---|---:|---:|---:|---:|---:|",
  );
  for (const loc of LOCALES) {
    const n = (p) => names.filter((x) => x.locale === loc && p(x.cls)).length;
    out.push(
      `| ${loc} | ${n((c) => c.startsWith("tabled"))} | ${n((c) => c === "conflict")} | ${n((c) => c.startsWith("reversed"))} | ${n((c) => c.startsWith("untabled"))} | ${n((c) => c.includes("multi"))} |`,
    );
  }
  out.push(
    "",
    "## Known variant forms (audit §5) — occurrences",
    "",
    "| Name | Form | Where (locale/book:count) |",
    "|---|---|---|",
  );
  for (const v of variants) out.push(`| ${v.name} | ${v.form} | ${v.where} |`);
  return `${out.join("\n")}\n`;
}

/** Check ids accepted by --check (exact ids or a family prefix: "S1" = S1a/S1b/S1c, not S10–S19). */
